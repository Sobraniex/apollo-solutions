const GALLERY_DATA = {
  domov: { src: "images/shots/domov.png", key: "cap.domov" },
  urnik: { src: "images/shots/urnik.png", key: "cap.urnik" },
  bolniki: { src: "images/shots/bolniki.png", key: "cap.bolniki" },
  "finance-izdani": { src: "images/shots/finance-izdani.png", key: "cap.bills" },
  "finance-pregled": { src: "images/shots/finance-pregled.png", key: "cap.overview" },
  kolektiv: { src: "images/shots/kolektiv.png", key: "cap.kolektiv" },
};

const galleryCaption = document.getElementById("galleryCaption");
const galleryImg = document.getElementById("galleryImg");
const galleryFrame = document.getElementById("galleryFrame");
const lightbox = document.getElementById("lightbox");
const lightboxImg = document.getElementById("lightboxImg");
const lightboxCap = document.getElementById("lightboxCap");
const galleryTabs = document.getElementById("galleryTabs");

function setGalleryTab(key) {
  const d = GALLERY_DATA[key];
  if (!d) return;
  galleryTabs.querySelectorAll(".gtab").forEach(b => {
    const on = b.dataset.tab === key;
    b.classList.toggle("on", on);
    b.setAttribute("aria-selected", on ? "true" : "false");
  });
  galleryImg.src = d.src;
  const dict = (I18N[localStorage.getItem("hds-lang") || "sl"]) || {};
  const txt = dict[d.key] || "";
  if (galleryCaption) galleryCaption.textContent = txt;
  if (lightboxImg) lightboxImg.src = d.src;
  if (lightboxCap) lightboxCap.textContent = txt;
}

if (galleryTabs) {
  galleryTabs.querySelectorAll(".gtab").forEach((b) =>
    b.addEventListener("click", () => setGalleryTab(b.dataset.tab))
  );
}
if (galleryFrame) {
  galleryFrame.addEventListener("click", () => {
    lightbox.classList.add("open");
    lightbox.setAttribute("aria-hidden", "false");
    document.body.style.overflow = "hidden";
  });
  galleryFrame.addEventListener("keydown", (e) => {
    if (e.key === "Enter" || e.key === " ") galleryFrame.click();
  });
}
function closeLightbox() {
  if (!lightbox) return;
  lightbox.classList.remove("open");
  lightbox.setAttribute("aria-hidden", "true");
  document.body.style.overflow = "";
}
if (lightbox) {
  lightbox.querySelector(".lightbox-close").addEventListener("click", () => closeLightbox());
  lightbox.addEventListener("click", (e) => { if (e.target === lightbox) closeLightbox(); });
  document.addEventListener("keydown", (e) => { if (e.key === "Escape") closeLightbox(); });
}
