const btn = document.getElementById("langBtn");
let lang = localStorage.getItem("hds-lang") || "sl";

function apply(next) {
  lang = next;
  localStorage.setItem("hds-lang", next);
  document.documentElement.lang = next;
  const dict = I18N[next];
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) el.textContent = dict[key];
  });
  btn.textContent = next === "sl" ? "EN" : "SL";
  if (typeof setGalleryTab === "function") {
    const cur = document.querySelector(".gtab.on");
    if (cur) setGalleryTab(cur.dataset.tab);
  }
}

btn.addEventListener("click", () => apply(lang === "sl" ? "en" : "sl"));
apply(lang);

